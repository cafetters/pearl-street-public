"""The proven-capacity parameter sweep (owner, Nov 19, plan step (h); pre-registered in
docs/plans/proven_capacity_experiment.md). Synthetic worlds only.

    python -m redteam.proven_sweep <shard config.yaml>      # the cloud launcher's form (--module redteam.proven_sweep)
    python -m redteam.proven_sweep --make configs/proven_sweep  # writes the pinned shard configs

A shard config has the launcher's keys (run_name, data_dir, start, end, m0_dir; checks only) and `points`: a list of
{scenario, budget_kw, reserve_kw, strength, twin}. Each point runs redteam.proven_scenarios.run with the pinned fixed
parameters (FIXED) and writes runs/<run_name>/<point>/...; summary.json holds one row per point.
"""
from __future__ import annotations

import argparse
import itertools
import json
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parents[1]
DAYS = 14
FIXED = {"step_kw": 100.0, "grow": 0.5, "cut": 0.5, "n0": 3, "clean_tol": 0.10, "existing_prior": [99.0, 1.0],
         "starter_fallback_kw": 1000.0}
GRID = {"budget_kw": [1000.0, 5000.0, 20000.0], "reserve_kw": [5000.0, 20000.0, 50000.0], "strength": [2.0, 6.0, 20.0]}
SCEN = {"no_newcomers": {},
        "honest_flood": {"k": 10, "honest_kw": 1500.0},
        "giant_liar": {"giant_real_kw": 1000.0, "giant_paper_kw": 30000.0},
        "sybil": {"m": 40, "sybil_real_kw": 100.0, "sybil_paper_kw": 1000.0}}
LIARS = ("giant_liar", "sybil")
LAUNCHER = {"data_dir": "../data", "start": "2023-01-12", "end": "2023-01-13", "slice_tz": "America/Chicago",
            "m0_dir": "runs/m0_jan12", "compare_to": "none", "seed": 1}


def proven_cfg(p: dict) -> dict:
    s = float(p["strength"])
    return {**FIXED, "new_prior": [s / 2.0, s / 2.0], "budget_kw": float(p["budget_kw"]),
            "reserve_kw": float(p["reserve_kw"])}


def points() -> list[dict]:
    out = []
    for sc in SCEN:
        for b, r, s in itertools.product(GRID["budget_kw"], GRID["reserve_kw"], GRID["strength"]):
            for twin in ((False, True) if sc in LIARS else (False,)):
                out.append({"scenario": sc, "budget_kw": b, "reserve_kw": r, "strength": s, "twin": twin})
    return out


def name_of(p: dict) -> str:
    return (f"{p['scenario']}_b{int(p['budget_kw'])}_r{int(p['reserve_kw'])}_s{int(p['strength'])}"
            + ("_twin" if p["twin"] else ""))


def make(dir_: Path, shards: int = 12) -> list[Path]:
    dir_.mkdir(parents=True, exist_ok=True)
    pts = points()
    paths = []
    for i in range(shards):
        cfg = {"run_name": f"pcsweep_{i:02d}", **LAUNCHER, "days": DAYS, "points": pts[i::shards]}
        p = dir_ / f"pcsweep_{i:02d}.yaml"
        p.write_text("# generated by python -m redteam.proven_sweep --make (pre-registered; do not edit)\n"
                     + yaml.safe_dump(cfg, sort_keys=False), encoding="utf-8")
        paths.append(p)
    return paths


def run_shard(cfg: dict) -> dict:
    from bench.runinfo import run_header
    from redteam.proven_scenarios import EXISTING_MW, run
    out = REPO / "runs" / str(cfg["run_name"])
    rows = []
    for p in cfg["points"]:
        r = run(p["scenario"], proven_cfg(p), out / name_of(p), days=int(cfg.get("days", DAYS)),
                honest_twin=bool(p["twin"]), existing=EXISTING_MW, **SCEN[p["scenario"]])
        r.pop("events", None)
        rows.append({"point": p, "name": name_of(p), **r})
    summary = {"header": run_header("redteam/proven_sweep.py", cfg, cfg.get("seed", 1)), "fixed": FIXED,
               "label": "[sim, synthetic]", "rows": rows}
    out.mkdir(parents=True, exist_ok=True)
    (out / "summary.json").write_text(json.dumps(summary, indent=1, default=str), encoding="utf-8")
    return summary


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("config", nargs="?")
    ap.add_argument("--make")
    a = ap.parse_args()
    if a.make:
        for p in make(REPO / a.make):
            print(p)
    elif a.config:
        s = run_shard(yaml.safe_load(Path(a.config).read_text(encoding="utf-8")))
        print(len(s["rows"]), "points")
    else:
        ap.error("give a shard config or --make")
